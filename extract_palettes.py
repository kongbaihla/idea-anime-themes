def collect():
    palettes = {}
    for name in idea_themes.PALETTES:
        p = dict(idea_themes.PALETTES[name])
        idea_themes.fix_palette(name, p)
        palettes[name] = p
    syntax = {}
    for theme in idea_roles.THEMES:
        idea_build.polish(theme)
        r = theme["roles"]
        syntax[theme["name"]] = {k: r[k]["fg"] for k in SYNTAX_ROLES}
    return palettes, syntax


def render():
    palettes, syntax = collect()
    return (HEADER
            + "PALETTES = "
            + pprint.pformat(palettes, indent=4, width=96, sort_dicts=False)
            + "\n\nEDITOR_ROLES = "
            + pprint.pformat(syntax, indent=4, width=96, sort_dicts=False)
            + "\n" + HELPERS)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=os.path.join(
        os.path.dirname(HERE), "blender-anime-themes", "anime_palettes.py"))
    args = ap.parse_args()
    body = render()
    with io.open(args.out, "w", encoding="utf-8", newline="\n") as f:
        f.write(body)
    palettes, syntax = collect()
    print(f"wrote {args.out}")
    print(f"  {len(palettes)} palettes, {len(syntax)} role sets, {len(body)} bytes")
    print("  now re-run blender_themes.py in that repository")


if __name__ == "__main__":
    main()
