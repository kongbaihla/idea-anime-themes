# --------------------------------------------------------------- helpers ----
def _rgb(h):
    h = h.lstrip("#")
    return tuple(int(h[i:i + 2], 16) for i in (0, 2, 4))


def _lum(h):
    def lin(c):
        c = c / 255.0
        return c / 12.92 if c <= 0.03928 else ((c + 0.055) / 1.055) ** 2.4
    r, g, b = _rgb(h)
    return 0.2126 * lin(r) + 0.7152 * lin(g) + 0.0722 * lin(b)


def contrast(c1, c2):
    a, b = _lum(c1), _lum(c2)
    return round((max(a, b) + 0.05) / (min(a, b) + 0.05), 2)


def _hls_hex(h, l, s):
    r, g, b = colorsys.hls_to_rgb(h, l, s)
    return "#{:02x}{:02x}{:02x}".format(
        max(0, min(255, round(r * 255))),
        max(0, min(255, round(g * 255))),
        max(0, min(255, round(b * 255))))


def adjust(fg, bg, target):
    """Nudge lightness only, until fg/bg meets the contrast target.

    The direction moves away from the background rather than assuming a light or
    dark theme, because several backgrounds here are mid-tone (gold, vermilion).
    """
    if not bg or contrast(fg, bg) >= target:
        return fg
    r, g, b = _rgb(fg)
    h, l, s = colorsys.rgb_to_hls(r / 255.0, g / 255.0, b / 255.0)
    brighter = _lum(fg) >= _lum(bg)
    lo, hi = (l, 1.0) if brighter else (0.0, l)
    for _ in range(48):
        mid = (lo + hi) / 2.0
        if contrast(_hls_hex(h, mid, s), bg) >= target:
            hi, lo = (mid, lo) if brighter else (hi, mid)
        else:
            lo, hi = (mid, hi) if brighter else (lo, mid)
    found = _hls_hex(h, hi if brighter else lo, s)
    if contrast(found, bg) < target:
        for cand in ("#ffffff", "#000000", _hls_hex(h, 1.0 if brighter else 0.0, s)):
            if contrast(cand, bg) >= target:
                return cand
    return found


